def _stringify(value: Any) -> str | None:
    if value is None:
        return None
    return str(value)


def catalogue_rows() -> list[dict[str, str | None]]:
    """Return TAP-shaped rows for the curated systems."""
    rows: list[dict[str, str | None]] = []
    for host, planets in _SYSTEMS:
        for planet in planets:
            row: dict[str, str | None] = {column: None for column in COLUMNS}
            merged = {**host, **planet, "pl_controv_flag": planet.get("pl_controv_flag", 0)}
            for key, value in merged.items():
                if key in row:
                    row[key] = _stringify(value)
            rows.append(row)
    return rows
